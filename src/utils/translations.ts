export function translateCategory(category: string, lang: Language): string {
  if (categoryTranslations[lang] && categoryTranslations[lang][category]) {
    return categoryTranslations[lang][category];
  }
  return category;
}

export function getRemedyTranslatedContent(remId: string, originalContent: any, lang: Language): any {
  if (!originalContent) return originalContent;

  const trans = remedyTranslations[remId]?.[lang];
  if (trans) {
    return {
      ...originalContent,
      title: trans.title,
      description: trans.description,
      benefits: trans.benefits,
      ingredients: trans.ingredients,
      preparation: trans.preparation,
      dosage: trans.dosage,
      warnings: trans.warnings
    };
  }

  return originalContent;
}
